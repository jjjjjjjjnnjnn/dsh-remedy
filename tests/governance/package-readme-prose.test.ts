import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { test } from 'node:test'
import { proseNumbers } from '../../scripts/lib/copy-policy.mjs'

const root = new URL('../../', import.meta.url)
const read = (path: string) => readFileSync(new URL(path, root), 'utf8')

const PACKAGE_READMES = ['packages/plugin/README.md', 'packages/core/README.md'] as const

test('a package README carries no prose number, so it cannot quote a stale one', () => {
  // P-0017, blind spot BS-13. `gate_copy` cannot see these pages: they are
  // hand-written, have no `output_sha256` and are not generated by the copy
  // channel. P-0014 pinned the CLI block; what was left was the prose. The
  // measured answer is that there is nothing numeric left to rot — and this test
  // keeps it that way instead of trusting a one-off measurement.
  //
  // `packages/core/README.md` is included because it is the page for the engine,
  // and it had exactly the same exposure.
  for (const page of PACKAGE_READMES) {
    const extra = proseNumbers(read(page))
    assert.deepEqual(
      extra,
      [],
      `${page} states a number in prose that no gate checks: ${extra.join(', ')}. ` +
        'Put it in the fact pack and the copy channel, or describe it without digits.',
    )
  }
})

test('every command a package README shows inside a fence is one the CLI dispatches', () => {
  // The other half of the exposure: a fenced block is the part a reader copies.
  // A block that shows a command the binary rejects is worse than no block.
  const cli = read('packages/plugin/src/cli.ts')
  const dispatched = new Set([...cli.matchAll(/case '([a-z-]+)':/g)].map((match) => match[1] ?? ''))
  assert.ok(dispatched.size >= 5, 'the CLI must dispatch its commands')

  const readme = read('packages/plugin/README.md')
  for (const block of readme.matchAll(/```[\w-]*\n([\s\S]*?)```/g)) {
    for (const line of (block[1] ?? '').split(/\r?\n/)) {
      const match = /^dsh-remedy ([a-z-]+)\s/.exec(line.trim())
      if (match === null) continue
      const command = match[1] ?? ''
      assert.ok(dispatched.has(command), `the packaged README shows \`dsh-remedy ${command}\`, which the CLI cannot dispatch`)
    }
  }

  // And the engine page must not describe a CLI at all: it is a library.
  const coreReadme = read('packages/core/README.md')
  assert.doesNotMatch(
    coreReadme,
    /```[\w-]*\n[^`]*dsh-remedy [a-z-]/,
    'packages/core/README.md must not document CLI commands',
  )
})
